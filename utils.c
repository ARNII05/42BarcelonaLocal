#include "push_swap.h"

int	ft_isnotdigit(int c)
{
	if (c >= 48 && c <= 57)
		return (0);
	return (1);
}

size_t	ft_strlen(const char *c)
{
	size_t	i;

	i = 0;
	while (c[i] != 0)
		i++;
	return (i);
}